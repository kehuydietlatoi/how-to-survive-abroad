// One-off: rasterise Natural Earth 110m land (public domain) into a 2°-cell bitset for the globe.
// usage: node scripts/build-landmask.mjs path/to/ne_110m_land.geojson
import { readFileSync, writeFileSync } from "node:fs";

const src = process.argv[2];
if (!src) throw new Error("usage: node scripts/build-landmask.mjs <ne_110m_land.geojson>");

const W = 180; // cells in longitude
const H = 90; // cells in latitude
const geo = JSON.parse(readFileSync(src, "utf8"));

const polys = [];
for (const f of geo.features) {
  const g = f.geometry;
  if (g.type === "Polygon") polys.push(g.coordinates);
  else if (g.type === "MultiPolygon") polys.push(...g.coordinates);
}

function inRing(x, y, ring) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}
// A polygon is its outer ring minus the holes.
const inPoly = (x, y, rings) => inRing(x, y, rings[0]) && !rings.slice(1).some((h) => inRing(x, y, h));

// Row 0 is the north pole; each cell is sampled at its centre.
const bits = new Uint8Array(Math.ceil((W * H) / 8));
let land = 0;
for (let r = 0; r < H; r++) {
  const lat = 90 - (r + 0.5) * (180 / H);
  for (let c = 0; c < W; c++) {
    const lon = -180 + (c + 0.5) * (360 / W);
    if (polys.some((p) => inPoly(lon, lat, p))) {
      const i = r * W + c;
      bits[i >> 3] |= 1 << (i & 7);
      land++;
    }
  }
}

const out = `// GENERATED by scripts/build-landmask.mjs from Natural Earth 110m land (public domain). Do not edit.
// ${W}x${H} equirectangular grid, row 0 = north pole, bit set = land.
const W = ${W};
const H = ${H};
const DATA = "${Buffer.from(bits).toString("base64")}";

let bytes = null;
function decode() {
  if (bytes) return bytes;
  const bin = atob(DATA);
  bytes = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i);
  return bytes;
}

export const LAND = { w: W, h: H };

/** Is the cell containing (lat, lon) land? */
export function isLand(lat, lon) {
  const r = Math.min(H - 1, Math.max(0, Math.floor(((90 - lat) / 180) * H)));
  const c = Math.min(W - 1, Math.max(0, Math.floor(((((lon + 180) % 360) + 360) % 360 / 360) * W)));
  const i = r * W + c;
  return (decode()[i >> 3] & (1 << (i & 7))) !== 0;
}
`;
writeFileSync(new URL("../src/ui/landmask.js", import.meta.url), out);
console.log(`land cells: ${land} / ${W * H}`);
